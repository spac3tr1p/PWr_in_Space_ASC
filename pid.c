void PID_Iteration(PIDType* const pid)
{
  float error = THETA_TARGET - pid->theta;
  pid->I += error * dt;
  pid->D = (error - pid->prev_error) / dt;

  float m = KP * error + KI * pid->I + KD * pid->D;

  if (m > U_MAX)      
  { 
    m = U_MAX; 
  }
  else if (m < U_MIN) 
  { 
    m = U_MIN; 
  }
  pid->u = m;
  pid->prev_error = error;
} // end: PID_Iteration


void PID_ThetaOmegaUpdate(PIDType* const pid)
{
  pid->omega += pid->u * dt;
  pid->theta += pid->omega * dt;
} // end: PID_ThetaOmegaUpdate



