/* GLOBAL DEFINES                                                                                                     */
/**********************************************************************************************************************/
#define THETA_TARGET 0.0f
#define THETA_START 10.0f

#define DURATION_SECONDS 10
#define UPDATE_HZ 1000
#define STEPS (DURATION_SECONDS * UPDATE_HZ)
/**********************************************************************************************************************/
/* TYPES                                                                                                              */
/**********************************************************************************************************************/

typedef struct {

  float prev_error;
  float theta;
  float omega;
  float I;
  float D;
  float u;

} PIDType;

